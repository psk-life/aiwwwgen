# Добавляем название категории в каждую карточку один раз при старте.
for _material in MATERIALS:
    _material["category_name"] = CATEGORY_NAMES.get(_material["category"], "")


@app.route("/")
def index():
    """Главная страница: герой-блок, фильтр и карточки материалов."""
    return render_template("index.html", materials=MATERIALS, categories=CATEGORIES)


@app.route("/material/<int:material_id>")
def material(material_id):
    """Страница отдельного материала по его идентификатору."""
    item = next((m for m in MATERIALS if m["id"] == material_id), None)
    if item is None:
        abort(404)
    others = [m for m in MATERIALS if m["id"] != item["id"]][:3]
    return render_template("material.html", material=item, others=others)


@app.errorhandler(404)
def page_not_found(_error):
    """Страница для несуществующих адресов."""
    return render_template("404.html"), 404


if __name__ == "__main__":
    # debug=True удобен при разработке: сервер сам перезапускается при правках
    app.run(debug=True)
